std_return = df['strategy_return'].std() #计算收益标准差(波动率)
sharpe_ratio = mean_return / std_return
sharpe_ratio = (
    mean_return / std_return
) * np.sqrt(50)
print("夏普比率:", sharpe_ratio)
if sharpe_ratio <= 1:
    print("策略水平一般")
elif (sharpe_ratio > 1) & (sharpe_ratio <=2):
    print("策略水平还不错")
elif (sharpe_ratio > 2) & (sharpe_ratio <=3):
    print("策略水平很强")

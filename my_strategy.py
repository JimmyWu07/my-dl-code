# PCA降维
pca = PCA(n_components=2)
X_pca = pca.fit_transform(X_scaled)
df['pca1'] = X_pca[:, 0] #价格 + 成交量的整体趋势和波动
df['pca2'] = X_pca[:, 1] #价格和成交量的背离、市场的异常波动

# --------------------------夏普比率部分 --------------------------
